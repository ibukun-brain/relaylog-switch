//! Minimal evidence types preserving the verified Relaylog export provenance.

use serde::Serialize;
use serde_json::Value;
use std::collections::BTreeMap;

use crate::agent_evidence::{
    AgentActor, AgentEvidenceConfidence, AgentEvidenceEvent, AgentEvidenceSource,
    UnsupportedAgentEvidence,
};
use crate::error::PrivacyError;
use crate::privacy::records_outside_private_intervals;

/// Provenance category attached to an evidence record.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum EvidenceProvenance {
    /// Captured by Relaylog as a terminal or shell observation.
    Observed,
    /// Reported by an operator through a Relaylog origin marker.
    OperatorReported,
    /// Reported by an AI-agent provider hook; not independently verified execution.
    AgentReported,
    /// Imported from another evidence source without independent verification.
    Imported,
    /// Generated by a downstream AI workflow; never parsed from Relaylog export.
    AiGenerated,
    /// Provenance is unknown and must not be treated as verified evidence.
    Unknown,
}

/// Local evidence reference based on the export's spool offset.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct EvidenceId(u64);

impl EvidenceId {
    /// Returns the byte offset in the encrypted spool recorded in the export.
    #[must_use]
    pub const fn spool_offset(self) -> u64 {
        self.0
    }

    /// Formats this reference for reports; it is unique only within one export.
    #[must_use]
    pub fn as_reference(self) -> String {
        format!("offset-{}", self.0)
    }
}

/// A capture record supported by the current Relaylog JSONL export contract.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum CaptureRecord {
    /// Terminal input bytes. Never included in a prepared agent bundle.
    Input {
        /// Raw bytes from the operator's terminal input stream.
        bytes: Vec<u8>,
    },
    /// Terminal output bytes. Sharing requires separate explicit consent.
    Output {
        /// Raw bytes from the child terminal output stream.
        bytes: Vec<u8>,
    },
    /// Shell metadata whose nested event fields are preserved as untrusted JSON.
    Shell {
        /// Opaque metadata object emitted by Relaylog's shell integration.
        event: Value,
    },
    /// Operator-reported origin metadata.
    Origin {
        /// Operator-supplied origin classification.
        value: String,
        /// How the classification was supplied.
        source: String,
    },
    /// Private-mode marker; markers themselves are never exposed to agents.
    Redaction {
        /// Whether private mode was enabled at this transition.
        enabled: bool,
    },
    /// A known wrapper containing an unknown record kind, retained for local review.
    Unknown {
        /// Unrecognized record type tag.
        record_type: String,
        /// Original untrusted record object.
        data: Value,
    },
    /// Versioned, minimized evidence from a Relaylog agent hook.
    Agent {
        /// Relaylog recording session that owns this observation.
        session_id: String,
        /// Validated provider-neutral evidence event.
        evidence: Box<AgentEvidenceEvent>,
    },
    /// An agent event whose schema version or event type is not understood.
    AgentUnsupported {
        /// Relaylog recording session that owns this observation.
        session_id: String,
        /// Safe unsupported-schema category, without the raw payload.
        reason: UnsupportedAgentEvidence,
    },
}

/// One validated, ordered item from a Relaylog export.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct EvidenceRecord {
    id: EvidenceId,
    provenance: EvidenceProvenance,
    record: CaptureRecord,
}

impl EvidenceRecord {
    /// Returns the export-local reference for this evidence item.
    #[must_use]
    pub const fn id(&self) -> EvidenceId {
        self.id
    }

    /// Returns whether this item is observed, operator-reported, AI-generated, or unknown.
    #[must_use]
    pub const fn provenance(&self) -> EvidenceProvenance {
        self.provenance
    }

    /// Returns the original record without inventing command output or timestamps.
    #[must_use]
    pub const fn record(&self) -> &CaptureRecord {
        &self.record
    }
}

/// A complete validated Relaylog export.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ExportedSession {
    records: Vec<EvidenceRecord>,
    capture_gaps: CaptureGapSummary,
    session_id: Option<String>,
}

impl ExportedSession {
    /// Returns records in the exact order emitted by the export.
    #[must_use]
    pub fn records(&self) -> &[EvidenceRecord] {
        &self.records
    }

    /// Returns the validated final capture-gap summary.
    #[must_use]
    pub const fn capture_gaps(&self) -> &CaptureGapSummary {
        &self.capture_gaps
    }

    /// Returns the Relaylog recording session ID when the export carries one.
    #[must_use]
    pub fn session_id(&self) -> Option<&str> {
        self.session_id.as_deref()
    }

    /// Returns content-free counts and ordering information for local inspection.
    pub fn summary(&self) -> Result<EvidenceSummary, PrivacyError> {
        let mut record_types = BTreeMap::new();
        let visible = records_outside_private_intervals(self)?;
        for record in &visible {
            let name = match record.record() {
                CaptureRecord::Input { .. } => "input".to_owned(),
                CaptureRecord::Output { .. } => "output".to_owned(),
                CaptureRecord::Shell { .. } => "shell".to_owned(),
                CaptureRecord::Origin { .. } => "origin".to_owned(),
                CaptureRecord::Redaction { .. } => "redaction".to_owned(),
                CaptureRecord::Unknown { .. } => "unknown".to_owned(),
                CaptureRecord::Agent { .. } => "agent".to_owned(),
                CaptureRecord::AgentUnsupported { .. } => "agent_unsupported".to_owned(),
            };
            *record_types.entry(name).or_insert(0) += 1;
        }

        Ok(EvidenceSummary {
            record_count: visible.len(),
            record_types,
            first_spool_offset: visible.first().map(|record| record.id().spool_offset()),
            last_spool_offset: visible.last().map(|record| record.id().spool_offset()),
            capture_gaps: self.capture_gaps.clone(),
            note: "Private intervals and their markers are omitted. Spool offsets preserve export order. Legacy shell records lack session IDs and timestamps; versioned agent records may supply them.",
        })
    }
}

/// Validated loss counters from the required final export summary.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub struct CaptureGapSummary {
    queue_dropped_records: u64,
    capacity_dropped_records: u64,
    truncated_at: Option<u64>,
}

/// Content-free summary suitable for local inspection.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub struct EvidenceSummary {
    record_count: usize,
    record_types: BTreeMap<String, usize>,
    first_spool_offset: Option<u64>,
    last_spool_offset: Option<u64>,
    capture_gaps: CaptureGapSummary,
    note: &'static str,
}

impl EvidenceSummary {
    /// Returns the number of records in the export.
    #[must_use]
    pub const fn record_count(&self) -> usize {
        self.record_count
    }

    /// Returns record counts by Relaylog record type, without record contents.
    #[must_use]
    pub const fn record_types(&self) -> &BTreeMap<String, usize> {
        &self.record_types
    }

    /// Returns the first spool offset in export order.
    #[must_use]
    pub const fn first_spool_offset(&self) -> Option<u64> {
        self.first_spool_offset
    }

    /// Returns the last spool offset in export order.
    #[must_use]
    pub const fn last_spool_offset(&self) -> Option<u64> {
        self.last_spool_offset
    }

    /// Returns the validated capture gap counters.
    #[must_use]
    pub const fn capture_gaps(&self) -> &CaptureGapSummary {
        &self.capture_gaps
    }

    /// Returns an explanation of the export's missing identifiers and times.
    #[must_use]
    pub const fn note(&self) -> &'static str {
        self.note
    }
}

impl CaptureGapSummary {
    /// Returns the number of records lost from the capture queue.
    #[must_use]
    pub const fn queue_dropped_records(&self) -> u64 {
        self.queue_dropped_records
    }

    /// Returns the number of records lost because the spool reached capacity.
    #[must_use]
    pub const fn capacity_dropped_records(&self) -> u64 {
        self.capacity_dropped_records
    }

    /// Returns the incomplete final record's spool offset, if one was detected.
    #[must_use]
    pub const fn truncated_at(&self) -> Option<u64> {
        self.truncated_at
    }
}

pub(crate) fn make_record(spool_offset: u64, record: CaptureRecord) -> EvidenceRecord {
    let provenance = match record {
        CaptureRecord::Origin { .. } => EvidenceProvenance::OperatorReported,
        CaptureRecord::Agent { ref evidence, .. } => match evidence.source().confidence() {
            AgentEvidenceConfidence::ShellObserved => EvidenceProvenance::Observed,
            AgentEvidenceConfidence::AgentReported => EvidenceProvenance::AgentReported,
            AgentEvidenceConfidence::Imported => EvidenceProvenance::Imported,
            AgentEvidenceConfidence::Unknown => EvidenceProvenance::Unknown,
        },
        CaptureRecord::Unknown { .. } | CaptureRecord::AgentUnsupported { .. } => {
            EvidenceProvenance::Unknown
        }
        _ => EvidenceProvenance::Observed,
    };
    EvidenceRecord {
        id: EvidenceId(spool_offset),
        provenance,
        record,
    }
}

/// Checks shell metadata against the currently verified Relaylog hook fields.
///
/// Unknown values are not projected into an agent bundle, even when the field
/// name itself is familiar.
pub(crate) fn is_supported_shell_event(event: &Value) -> bool {
    let Some(object) = event.as_object() else {
        return false;
    };
    let Some(event_type) = object.get("type").and_then(Value::as_str) else {
        return false;
    };
    let allowed_fields: &[&str] = match event_type {
        "started" => &[
            "type",
            "command",
            "cwd",
            "shell_depth",
            "command_text_scope",
            "child_interval",
            "actor",
            "source",
        ],
        "finished" => &[
            "type",
            "exit_code",
            "cwd",
            "duration_millis",
            "boundary_quality",
            "actor",
            "source",
        ],
        _ => return false,
    };
    if !object
        .keys()
        .all(|field| allowed_fields.contains(&field.as_str()))
        || !optional_shell_actor_is_valid(object.get("actor"))
        || !optional_shell_source_is_valid(object.get("source"))
    {
        return false;
    }

    match event_type {
        "started" => {
            optional_string(object.get("command"))
                && optional_string(object.get("cwd"))
                && optional_u32(object.get("shell_depth"))
                && optional_one_of(
                    object.get("command_text_scope"),
                    &["first_simple_command", "complete_line"],
                )
                && optional_one_of(object.get("child_interval"), &["unstructured"])
        }
        "finished" => {
            optional_i32(object.get("exit_code"))
                && optional_string(object.get("cwd"))
                && optional_u64(object.get("duration_millis"))
                && optional_one_of(object.get("boundary_quality"), &["unpaired"])
        }
        _ => false,
    }
}

fn optional_shell_actor_is_valid(value: Option<&Value>) -> bool {
    value.is_none_or(|value| {
        serde_json::from_value::<AgentActor>(value.clone()).is_ok_and(|actor| {
            optional_text_is_valid(actor.name(), 128)
                && optional_text_is_valid(actor.id(), 256)
                && optional_text_is_valid(actor.provider(), 64)
                && optional_text_is_valid(actor.session_id(), 256)
                && optional_text_is_valid(actor.parent_session_id(), 256)
        })
    })
}

fn optional_shell_source_is_valid(value: Option<&Value>) -> bool {
    value.is_none_or(|value| {
        serde_json::from_value::<AgentEvidenceSource>(value.clone()).is_ok_and(|source| {
            optional_text_is_valid(source.provider(), 64)
                && text_is_valid(source.observation_method(), 64, true)
        })
    })
}

fn optional_text_is_valid(value: Option<&str>, max_bytes: usize) -> bool {
    value.is_none_or(|value| text_is_valid(value, max_bytes, false))
}

fn text_is_valid(value: &str, max_bytes: usize, non_empty: bool) -> bool {
    value.len() <= max_bytes && (!non_empty || !value.is_empty()) && !value.contains('\0')
}

fn optional_string(value: Option<&Value>) -> bool {
    value.is_none_or(Value::is_string)
}

fn optional_u32(value: Option<&Value>) -> bool {
    value.is_none_or(|value| {
        value
            .as_u64()
            .is_some_and(|number| u32::try_from(number).is_ok())
    })
}

fn optional_u64(value: Option<&Value>) -> bool {
    value.is_none_or(|value| value.as_u64().is_some())
}

fn optional_i32(value: Option<&Value>) -> bool {
    value.is_none_or(|value| {
        value
            .as_i64()
            .is_some_and(|number| i32::try_from(number).is_ok())
    })
}

fn optional_one_of(value: Option<&Value>, allowed: &[&str]) -> bool {
    value.is_none_or(|value| value.as_str().is_some_and(|value| allowed.contains(&value)))
}

pub(crate) fn make_gaps(
    queue_dropped_records: u64,
    capacity_dropped_records: u64,
    truncated_at: Option<u64>,
) -> CaptureGapSummary {
    CaptureGapSummary {
        queue_dropped_records,
        capacity_dropped_records,
        truncated_at,
    }
}

pub(crate) fn make_session(
    records: Vec<EvidenceRecord>,
    capture_gaps: CaptureGapSummary,
    session_id: Option<String>,
) -> ExportedSession {
    ExportedSession {
        records,
        capture_gaps,
        session_id,
    }
}
